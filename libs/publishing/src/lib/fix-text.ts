import { codeFence, escapeInline, neutralizeQuickActions } from './sanitize';

/** What the fix texts need: finding title (model text) and the proposal (patch + model explanation). */
export interface FixTextInput {
  readonly finding: { readonly title: string; readonly severity: string; readonly category: string };
  readonly proposal: {
    readonly id: string;
    readonly fingerprint: string;
    readonly filePath: string;
    readonly explanation: string;
    readonly patch: string;
  };
}

/** Single line of plain text: control characters and line breaks removed, length capped. */
export function plainLine(text: string, max: number): string {
  const cleaned = text
    // eslint-disable-next-line no-control-regex -- stripping control characters is the point
    .replace(/[\x00-\x1f\x7f]+/g, ' ') // \s below also covers U+2028/U+2029
    .replace(/\s+/g, ' ')
    .trim();
  return cleaned.length > max ? `${cleaned.slice(0, max - 1).trimEnd()}…` : cleaned;
}

/**
 * Commit message for an approved fix. The subject is derived from the model-written finding title,
 * so it is reduced to one plain line; the human sees and approves the exact message.
 */
export function fixCommitMessage(input: FixTextInput): string {
  const subject = `fix: ${plainLine(input.finding.title, 64) || 'apply AI review fix'}`;
  return [
    subject,
    '',
    `Resolves AI review finding ${input.proposal.fingerprint.slice(0, 12)} (${plainLine(input.finding.severity, 20)} ${plainLine(input.finding.category, 40)})`,
    `in ${plainLine(input.proposal.filePath, 200)}.`,
    '',
    `Proposed by AI Code Review Agent (fix ${input.proposal.id.slice(0, 8)}) and applied after human approval.`,
  ].join('\n');
}

/** Title and body for the MR/PR. Model text is escaped; quick actions and mentions neutralised. */
export function fixReviewRequestText(input: FixTextInput): { title: string; description: string } {
  const title = `fix: ${plainLine(input.finding.title, 180) || 'AI review fix'}`;
  const body = [
    '## AI-proposed fix',
    '',
    `**Finding:** ${escapeInline(input.finding.title)} (${escapeInline(input.finding.severity)}, ${escapeInline(input.finding.category)}) in \`${input.proposal.filePath.replace(/`/g, '')}\``,
    '',
    `**What changes and why:** ${escapeInline(input.proposal.explanation)}`,
    '',
    // Opening fence gets the "diff" language tag; the fence length already outgrows any backticks in the patch.
    codeFence(input.proposal.patch).replace(/^(`{3,})\n/, '$1diff\n'),
    '',
    '---',
    `This change was generated by the AI Code Review Agent (fix ${input.proposal.id.slice(0, 8)}) and pushed after explicit human approval.`,
    'It is **not** merged automatically — review it like any other change.',
  ].join('\n');
  return { title, description: neutralizeQuickActions(body) };
}

import { DatePipe } from '@angular/common';
import { httpResource } from '@angular/common/http';
import { ChangeDetectionStrategy, Component, computed, inject, input, signal } from '@angular/core';
import { Router, RouterLink } from '@angular/router';
import { FixDetailSchema } from '@acra/shared-contracts';
import { errorMessage } from '../../core/api/api-error';
import { DashboardApi } from '../../core/api/dashboard-api';
import { hasRole } from '../../core/auth/roles';
import { SessionStore } from '../../core/auth/session.store';
import { AsyncState } from '../../shared/ui/async-state';
import { Badge } from '../../shared/ui/badge';
import { DiffView } from '../../shared/ui/diff-view';
import { ShortShaPipe, UsdPipe } from '../../shared/ui/pipes';

/**
 * A fix proposal with its exact patch. From here a member requests approval for the next step:
 * push (branch + one commit) or open (merge/pull request). Merging is never offered.
 */
@Component({
  selector: 'acr-fix-detail-page',
  imports: [AsyncState, Badge, DatePipe, DiffView, RouterLink, ShortShaPipe, UsdPipe],
  template: `
    <p><a [routerLink]="['/o', orgId(), 'fixes']">← Fix proposals</a></p>
    <acr-async-state
      [loading]="fix.isLoading()"
      [error]="loadError()"
      [hasData]="fix.hasValue()"
      (retry)="fix.reload()"
    >
      @if (fix.value(); as f) {
        <div class="page-header">
          <div>
            <h1>{{ f.findingTitle }}</h1>
            <p class="muted">
              {{ f.repositoryName }} · <code>{{ f.filePath }}</code> · +{{ f.additions }} −{{ f.deletions }}
            </p>
          </div>
          <acr-badge [value]="f.status" />
        </div>

        <div class="card">
          <dl class="details">
            <dt>Finding</dt>
            <dd><a [routerLink]="['/o', orgId(), 'findings', f.findingId]">open finding</a></dd>
            <dt>Reviewed commit</dt>
            <dd>
              <code>{{ f.baseSha | shortSha }}</code>
            </dd>
            <dt>Fix branch</dt>
            <dd>
              <code>{{ f.branch }}</code> → <code>{{ f.targetBranch }}</code>
            </dd>
            <dt>Patch SHA-256</dt>
            <dd>
              <code class="small">{{ f.patchSha256 }}</code>
            </dd>
            <dt>Generated by</dt>
            <dd>{{ f.provider }} / {{ f.model }} · {{ f.costUsd | usd }}</dd>
            <dt>Proposed</dt>
            <dd>{{ f.createdAt | date: 'medium' }}</dd>
            @if (f.commitSha) {
              <dt>Commit</dt>
              <dd>
                <code>{{ f.commitSha | shortSha }}</code>
              </dd>
            }
            @if (f.reviewRequestUrl) {
              <dt>Merge/pull request</dt>
              <dd>
                <a [href]="f.reviewRequestUrl" target="_blank" rel="noopener noreferrer">{{ f.reviewRequestUrl }}</a>
              </dd>
            }
          </dl>
        </div>

        <h2>Why (model explanation, unverified)</h2>
        <p class="untrusted">{{ f.explanation }}</p>

        <h2>Patch</h2>
        <acr-diff-view [patch]="f.patch" [label]="'Patch for ' + f.filePath" />

        <h2>Next step</h2>
        @if (message(); as m) {
          <p class="banner banner-error" role="alert">{{ m }}</p>
        }
        @switch (f.nextStep) {
          @case ('push') {
            <p>
              Create the branch <code>{{ f.branch }}</code> with one commit containing exactly this patch.
            </p>
          }
          @case ('open') {
            <p>
              Open a merge/pull request from <code>{{ f.branch }}</code> into <code>{{ f.targetBranch }}</code>. It will
              not be merged automatically.
            </p>
          }
          @default {
            <p class="muted">No further step is available for a {{ f.status }} fix.</p>
          }
        }
        @if (f.nextStep) {
          @if (canRequest()) {
            <button type="button" class="btn btn-primary" (click)="request(f.nextStep)" [disabled]="requesting()">
              Request approval to {{ f.nextStep === 'push' ? 'push the fix branch' : 'open the merge/pull request' }}
            </button>
          } @else {
            <p class="muted">Viewers cannot request approvals.</p>
          }
        }
      }
    </acr-async-state>
  `,
  changeDetection: ChangeDetectionStrategy.OnPush,
})
export class FixDetailPage {
  private readonly api = inject(DashboardApi);
  private readonly session = inject(SessionStore);
  private readonly router = inject(Router);
  readonly orgId = input.required<string>();
  readonly fixId = input.required<string>();

  protected readonly fix = httpResource(() => this.api.orgUrl(this.orgId(), `/fixes/${this.fixId()}`), {
    parse: (v) => FixDetailSchema.parse(v),
  });
  protected readonly loadError = computed(() => (this.fix.error() ? errorMessage(this.fix.error()) : null));
  protected readonly canRequest = computed(() => hasRole(this.session.membership(this.orgId())?.role, 'MEMBER'));
  protected readonly requesting = signal(false);
  protected readonly message = signal<string | null>(null);

  protected async request(step: 'push' | 'open'): Promise<void> {
    this.requesting.set(true);
    this.message.set(null);
    try {
      const approval = await this.api.requestApproval(this.orgId(), { fixId: this.fixId(), step, ttlHours: 24 });
      await this.router.navigate(['/o', this.orgId(), 'approvals', approval.id]);
    } catch (error) {
      this.message.set(errorMessage(error));
    } finally {
      this.requesting.set(false);
    }
  }
}
